export function createEmojiPicker(onSelect) {
  const container = document.getElementById('emoji-picker');
  let currentCat = 0;

  // Category tabs
  const catsEl = document.createElement('div');
  catsEl.className = 'emoji-cats';
  EMOJI_CATEGORIES.forEach((cat, i) => {
    const btn = document.createElement('button');
    btn.className = 'emoji-cat-btn' + (i === 0 ? ' active' : '');
    btn.textContent = cat.icon;
    btn.title = cat.name;
    btn.addEventListener('click', () => {
      currentCat = i;
      document.querySelectorAll('.emoji-cat-btn').forEach((b, j) => {
        b.classList.toggle('active', j === i);
      });
      renderEmojis();
    });
    catsEl.appendChild(btn);
  });

  const gridEl = document.createElement('div');
  gridEl.className = 'emoji-grid';

  function renderEmojis() {
    gridEl.innerHTML = '';
    EMOJI_CATEGORIES[currentCat].emojis.forEach(emoji => {
      const btn = document.createElement('button');
      btn.className = 'emoji-btn';
      btn.textContent = emoji;
      btn.addEventListener('click', () => onSelect(emoji));
      gridEl.appendChild(btn);
    });
  }

  container.innerHTML = '';
  container.appendChild(catsEl);
  container.appendChild(gridEl);
  renderEmojis();
}
